DF={}
for words in AUTO_WORDS.values():
    for token in words:DF[token]=DF.get(token,0)+1
AUTO_WEIGHTS={mode:{token:1.0/DF[token] for token in words} for mode,words in AUTO_WORDS.items()}

def last_user_text(messages):
    for message in reversed(messages or []):
        if isinstance(message,dict) and message.get("role")=="user":
            content=message.get("content")
            if isinstance(content,list):return " ".join(str(p.get("text", "")) for p in content if isinstance(p,dict))
            return str(content or "")
    return ""

def auto_pick(text,allowed):
    # Cline's user goal outranks the surrounding environment/tool transcript.
    task=re.search(r"<task>([\s\S]*?)</task>",text or "",re.I)
    if task:text=task.group(1)
    else:text=re.split(r"<environment_details>|<tool_result>",text or "",maxsplit=1,flags=re.I)[0]
    hits=set(re.findall(r"[a-zа-яё0-9][a-zа-яё0-9+#'-]{1,}",text[:14000].lower()))
    best,score,tied=None,0.0,False
    for mode,weights in AUTO_WEIGHTS.items():
        if not all(p in allowed for p in mode.split("+")):continue
        value=sum(weights[t] for t in hits if t in weights)
        if value>score:best,score,tied=mode,value,False
        elif value==score and value>0 and mode!=best:tied=True
    return best if best and score>=0.4 and not tied else None

class AuthorModes:
    def __init__(self,source):
        match=re.search(r"set\s+reason_mods\s*=\s*(\[[^\]]+\])",source or "")
        try:modes=ast.literal_eval(match.group(1)) if match and "{REASON:" in source else []
        except (ValueError,SyntaxError):modes=[]
        self.modes=frozenset(x for x in modes if isinstance(x,str))
        self.supported="ultra" in self.modes
        self.blocks={}
    def valid(self,value):
        if value in (None,"","off","native"):return True
        if not isinstance(value,str) or len(value)>100:return False
        if value in ("auto","adaptive"):return self.supported
        return self.supported and len(value.split("+"))<=2 and all(x in self.modes and x!="off" for x in value.split("+"))
    def tag(self,text):
        match=re.match(r"\s*\{REASON:([a-z0-9+]{1,100})\}",text or "")
        if not match:return None
        value=match.group(1);candidate=value[1:] if value.startswith("i") else value
        return value if candidate in self.modes or self.valid(candidate) and "+" in candidate else None
    def selection(self,messages,kwargs):
        raw=kwargs.get("author_mode");tag=self.tag(last_user_text(messages))
        if not tag and raw is None:
            for message in messages or []:
                if message.get("role")=="user":
                    content=message.get("content");candidate=self.tag(content) if isinstance(content,str) else None
                    if candidate and content.strip()=="{REASON:"+candidate+"}":tag=candidate
                    break
        if raw is not None and not self.valid(raw):raise ValueError("Unsupported author reasoning mode")
        if raw not in (None,"","off","native") and not self.supported:raise ValueError("This template does not support author reasoning modes")
        value=tag or raw;off=False
        if tag and tag.startswith("i"):value=tag[1:];off=True
        if value in ("auto","adaptive"):value=auto_pick(last_user_text(messages),self.modes)
        if value in ("off","native",""):value=None
        return value,off,raw
    def kwargs(self,messages,kwargs):
        mode,off,_=self.selection(messages,kwargs)
        return {**kwargs,**({"enable_thinking":False} if off else {})}
    def render(self,render,messages,tools,add_generation_prompt,kwargs):
        mode,off,raw=self.selection(messages,kwargs)
        # No explicit author-mode field: preserve every original template byte.
        if raw is None and not (mode and "+" in mode):return render(messages=messages,tools=tools,add_generation_prompt=add_generation_prompt,**kwargs)
        kw=dict(kwargs);kw.pop("author_mode",None)
        if off:kw["enable_thinking"]=False
        clean=[]
        for message in messages:
            message=dict(message);content=message.get("content")
            def strip(text):
                return re.sub(r"\{REASON:([a-z0-9+]{1,100})\}",lambda m:"" if self.tag(m.group(0)) else m.group(0),text)
            if isinstance(content,str):message["content"]=strip(content)
            elif isinstance(content,list):message["content"]=[{**part,"text":strip(part["text"])} if isinstance(part,dict) and isinstance(part.get("text"),str) else part for part in content]
            clean.append(message)
        if mode:kw["reasoning_effort"]=mode.split("+")[0]
        result=render(messages=clean,tools=tools,add_generation_prompt=add_generation_prompt,**kw)
        if mode and "+" in mode:
            a,b=mode.split("+")
            def block(name):
                if name not in self.blocks:
                    probe=render(messages=[{"role":"user","content":"x"}],tools=None,add_generation_prompt=False,reasoning_effort=name,enable_thinking=True)
                    match=re.search(r"<\|im_start\|>system\n([\s\S]*?)<\|im_end\|>",probe)
                    self.blocks[name]=match.group(1).strip() if match else ""
                return self.blocks[name]
            ba,bb=block(a),block(b)
            if not ba or not bb or ba not in result:raise ValueError("This author-mode pair cannot be rendered safely")
            bridge="The first block frames reasoning. The second block frames the final answer: its voice and wrapper close the reply; the wrapper of your previous message does not carry over. Preserve tool schemas and caller instructions."
            result=result.replace(ba,ba+"\n\n"+bridge+"\n\n"+bb,1)
        return result
